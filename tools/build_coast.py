#!/usr/bin/env python3
"""Detailed modern land and coastline, for zooming in on the last few thousand years.

Source: Natural Earth 1:10m land and coastline (public domain):
    https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_land.geojson
    https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_coastline.geojson

Cut into 10-degree tiles (land slightly overlapping so tiles join without cracks; coastline cut exactly,
so no false edges are inked), simplified to about 500 m, stored to about 1 km, packed in the same varint
scheme as the other layers. One small file per tile in tiles/coast/, plus an index embedded in the page.
The page uses them only when zoomed in and only while the sea stood where it stands now.

Usage: python3 -I build_coast.py ne_10m_land.geojson ne_10m_coastline.geojson tiles/coast tools/source/coast-index.js
"""
import sys, os, json
from shapely.geometry import shape, box, Polygon, MultiPolygon, LineString, MultiLineString, GeometryCollection
from shapely.geometry.polygon import orient
from shapely.strtree import STRtree

land_f, coast_f, out, index = sys.argv[1:5]
TILE, TOL = 10, 0.005
land = [shape(f['geometry']).buffer(0) for f in json.load(open(land_f))['features']]
coast = [shape(f['geometry']) for f in json.load(open(coast_f))['features']]
lt, ct = STRtree(land), STRtree(coast)
A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
def packer():
    buf = []
    def u(n):
        while True:
            c = n & 31; n >>= 5
            buf.append(A[c | (32 if n else 0)])
            if not n: break
    def sz(n): u(-n * 2 - 1 if n < 0 else n * 2)
    def put(coords, closed):
        pts = []
        for x, y in (coords[:-1] if closed else coords):
            q = (round(x * 100), round(y * 100))
            if not pts or q != pts[-1]: pts.append(q)
        u(len(pts)); px = py = 0
        for x, y in pts: sz(x - px); sz(y - py); px, py = x, y
    return buf, u, put
def parts(g, kinds):
    if g.is_empty: return []
    if isinstance(g, kinds[0]): return [g]
    if isinstance(g, (kinds[1], GeometryCollection)): return [p for q in g.geoms for p in parts(q, kinds)]
    return []
os.makedirs(out, exist_ok=True)
have, total = [], 0
for ty in range(180 // TILE):
    for tx in range(360 // TILE):
        lo0, la1 = -180 + tx * TILE, 90 - ty * TILE
        cell, pad = box(lo0, la1 - TILE, lo0 + TILE, la1), box(lo0 - 0.03, la1 - TILE - 0.03, lo0 + TILE + 0.03, la1 + 0.03)
        polys = []
        for i in lt.query(pad):
            g = land[i].intersection(pad)
            for p in parts(g.simplify(TOL, preserve_topology=True), (Polygon, MultiPolygon)):
                if p.area < 0.0004: continue                                   # specks under ~2 km across
                p = orient(p, sign=-1.0); polys.append([list(p.exterior.coords)] + [list(h.coords) for h in p.interiors if Polygon(h).area > 0.0004])
        lines = []
        for i in ct.query(cell):
            g = coast[i].intersection(cell)
            for l in parts(g.simplify(TOL), (LineString, MultiLineString)):
                if len(l.coords) > 1: lines.append(list(l.coords))
        if not polys and not lines: continue
        buf, u, put = packer()
        u(len(polys))
        for rings in polys:
            u(len(rings))
            for r in rings: put(r, True)
        u(len(lines))
        for l in lines: put(l, False)
        s = ''.join(buf); total += len(s)
        open(f'{out}/{tx}_{ty}.txt', 'w').write(s); have.append(f'{tx}_{ty}')
open(index, 'w').write('/* Which detailed-coast tiles exist — GENERATED by tools/build_coast.py from Natural Earth 1:10m. */\n'
                       f'const COAST_TILE = {TILE};\nconst COAST_HAVE = "' + ','.join(have) + '";\n')
print(f'{len(have)} tiles, {total // 1024} KB', file=sys.stderr)
