#!/usr/bin/env python3
"""Terrain texture for zooming in: today's ridges, valleys and plains as light and shadow.

Source: the 2-arc-minute shaded-relief image of the world (shadedrelief.jpg, 10800 x 5400) shipped in
the `basemap-data` package on PyPI (matplotlib/basemap, LGPL; the image itself derives from Natural
Earth's public-domain shaded relief):

    pip download basemap-data==2.0.0 --no-deps -d bmd
    python3 -m zipfile -e bmd/basemap_data-2.0.0-py3-none-any.whl bmd/x

Only the shading is kept: the image is turned to grey, the broad colour bands are subtracted (so the
page's own land colours show through), and the sea is set to plain grey. Grey 128 means "no change";
the page lays the tiles over the land with an overlay blend. Three levels of detail, 0 = whole world.

Usage: python3 -I build_hillshade.py bmd/x/mpl_toolkits/basemap_data/shadedrelief.jpg tiles/relief tools/source/hill-index.js
"""
import sys, os
import numpy as np
from PIL import Image, ImageFilter

src, out = sys.argv[1:3]
Image.MAX_IMAGE_PIXELS = None
rgb = np.asarray(Image.open(src).convert('RGB')).astype(np.float32)
R, G, B = rgb[..., 0], rgb[..., 1], rgb[..., 2]
land = ~((B > R + 22) & (B >= G))                       # the image's sea is light blue
gray = 0.30 * R + 0.59 * G + 0.11 * B
def box(a, r, axis):
    # running mean over 2r+1 cells along one axis (wrapping east-west, clamped north-south)
    pad = [(0, 0), (0, 0)]; pad[axis] = (r + 1, r)
    c = np.cumsum(np.pad(a, pad, mode='wrap' if axis == 1 else 'edge'), axis=axis, dtype=np.float64)
    hi = np.take(c, np.arange(2 * r + 1, c.shape[axis]), axis=axis); lo = np.take(c, np.arange(0, c.shape[axis] - 2 * r - 1), axis=axis)
    return ((hi - lo) / (2 * r + 1)).astype(np.float32)
def blur(a, r):
    for _ in range(3): a = box(box(a, r, 0), r, 1)          # three box passes ~ a Gaussian
    return a
m = land.astype(np.float32)
base = blur(gray * m, 10) / np.maximum(blur(m, 10), 1e-3)  # local mean of the land only: no halo at coasts
detail = np.clip(128 + (gray - base) * 2.4, 0, 255)
near = ~land
for dy in (-2, -1, 0, 1, 2):                             # the source draws a pale line along every coast: keep it out
    for dx in (-2, -1, 0, 1, 2):
        near = near | np.roll(np.roll(~land, dy, 0), dx, 1)
detail[near] = 128
H, W = detail.shape                                      # 5400 x 10800: 30 pixels per degree
img = Image.fromarray(detail.astype(np.uint8), mode='L')
os.makedirs(out, exist_ok=True)
levels = [(0, 2.5, 360), (1, 10, 45), (2, 30, 15)]       # level, pixels per degree, tile size in degrees
total = 0; kept = 0
for z, ppd, deg in levels:
    lvl = img.resize((int(360 * ppd), int(180 * ppd)), Image.LANCZOS) if ppd != 30 else img
    arr = np.asarray(lvl)
    tp = int(deg * ppd)
    os.makedirs(f'{out}/z{z}', exist_ok=True)
    for ty in range(int(180 // min(deg, 180)) if deg < 360 else 1):
        for tx in range(int(360 // deg)):
            y0, x0 = ty * tp, tx * tp
            tile = arr[y0:y0 + (tp if deg < 360 else arr.shape[0]), x0:x0 + tp]
            total += 1
            if z > 0 and np.abs(tile.astype(np.int16) - 128).max() < 3: continue    # all sea: skip
            Image.fromarray(tile).save(f'{out}/z{z}/{tx}_{ty}.jpg', quality=72, optimize=True); kept += 1
    print(f'  level {z}: {ppd} px/degree, {deg}-degree tiles', file=sys.stderr)
# which tiles exist, so the page never asks for a sea tile that was skipped
have = {z: sorted(f[:-4] for f in os.listdir(f'{out}/z{z}') if f.endswith('.jpg')) for z, _, _ in levels}
open(sys.argv[3] if len(sys.argv) > 3 else f'{out}/have.js', 'w').write(
    '/* Which terrain tiles exist (the rest are open sea) — GENERATED by tools/build_hillshade.py. */\n'
    'const HILL_HAVE = ' + '{' + ','.join(f'{z}:"' + ','.join(have[z]) + '"' for z in have) + '};\n')
size = sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(out) for f in fs)
print(f'{kept} of {total} tiles kept, {size // 1024} KB', file=sys.stderr)
