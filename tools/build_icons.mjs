// Builds tools/source/icons-data.js: the line icons the page uses, from Lucide (ISC licence) plus four drawn for this
// atlas in the same style. Only the icons named in tools/source/icon_map.js (and ICON_EXTRA below) are kept, as shape
// lists the page turns into inline SVG (ico() in app.js) or canvas paths (drawIcon()).
//
//   npm i --ignore-scripts lucide-static@1.70.0          (in any scratch folder; the page never needs it)
//   node tools/build_icons.mjs <that folder>/node_modules/lucide-static/icon-nodes.json
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const HERE = path.dirname(new URL(import.meta.url).pathname);
const { EMOJI_ICON } = require(path.join(HERE, 'source', 'icon_map.js'));
const src = process.argv[2];
if (!src) { console.error('usage: node tools/build_icons.mjs <lucide-static>/icon-nodes.json'); process.exit(1); }
const nodes = JSON.parse(fs.readFileSync(src, 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(path.dirname(src), 'package.json'), 'utf8')).version;
// icons the code asks for by name, beyond the emoji table
const ICON_EXTRA = ['paw-print', 'git-fork', 'plus', 'minus', 'rotate-ccw', 'info', 'chevron-right', 'x'];
// drawn for this atlas: 24×24, stroke 2, round ends, like Lucide
const CUSTOM = {
  volcano: [['path', { d: 'M3 20 9 10h6l6 10Z' }], ['path', { d: 'M12 7V3' }], ['path', { d: 'm9 6-1.5-1.5' }], ['path', { d: 'm15 6 1.5-1.5' }]],
  meteor: [['circle', { cx: '8', cy: '16', r: '4' }], ['path', { d: 'm11 13 8-8' }], ['path', { d: 'm13.5 17 7-7' }], ['path', { d: 'm7 10.5 7-7' }]],
  mushroom: [['path', { d: 'M4 12a8 8 0 0 1 16 0Z' }], ['path', { d: 'M10 12v6a2 2 0 0 0 4 0v-6' }]],
  rock: [['path', { d: 'm4 19 2-8 5-4 6 2 3 10Z' }], ['path', { d: 'm11 7 1 5 5-3' }]],
};
const want = [...new Set([...Object.values(EMOJI_ICON), ...ICON_EXTRA])].sort();
const out = {}, missing = [];
for (const n of want) {
  const s = CUSTOM[n] || nodes[n];
  if (!s) { missing.push(n); continue; }
  out[n] = s.map(([tag, a]) => [tag, Object.fromEntries(Object.entries(a).filter(([k]) => k !== 'key'))]);
}
if (missing.length) { console.error('not in Lucide ' + version + ' and not drawn here: ' + missing.join(', ')); process.exit(1); }
const js = `/* Line icons — GENERATED by tools/build_icons.mjs from Lucide ${version} (ISC licence, lucide.dev) and four drawn
   for this atlas (volcano, meteor, mushroom, rock). ICONS[name] = [[tag, attributes], ...] on a 24×24 grid, stroke 2. */
const ICONS = ${JSON.stringify(out)};
const ICON_SOURCE = 'Lucide ${version}';
if (typeof module !== 'undefined') module.exports = { ICONS };
`;
fs.writeFileSync(path.join(HERE, 'source', 'icons-data.js'), js);
console.log(`${Object.keys(out).length} icons (${Object.keys(CUSTOM).filter(k => want.includes(k)).length} drawn here), ${(js.length / 1024).toFixed(1)} KB`);
