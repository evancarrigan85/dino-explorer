#!/usr/bin/env python3
"""Today's gravity shape of the Earth (the geoid), for the globe's "real shape" view.

The geoid is the shape the sea would take if it were still and spread under the land: the level that gravity
pulls water to. It rises and falls around the smooth, slightly flattened ellipse the Earth is usually drawn as
(WGS84) by at most about 100 m — 107 m below it south of Sri Lanka, 86 m above it over New Guinea.

Source: EGM2008, the Earth Gravitational Model 2008 (Pavlis et al. 2012, Journal of Geophysical Research 117,
B04406), geoid heights above the WGS84 ellipsoid on a 2.5-arc-minute grid, from the NetCDF copy in Zenodo
10.5281/zenodo.14537811 (C. Holmes, CC BY 4.0; derived from the US National Geospatial-Intelligence Agency's
public release), file EGM2008_2p5arcmin.nc4.

Writes tools/source/geoid-data.js: GEOID = { step, w, h, unit, low, high, peak, packed } — the mean height in each 2-degree cell,
rows from 90°S to 90°N (h = 91 rows, centred on every even latitude), columns from 180°W (w = 180, centred on
every even longitude, wrapping), smoothed over about 2°, in half metres, each row packed as zig-zag differences
(the page's usual code). low and high: where the smoothed grid is lowest and highest; peak: the lowest and highest
heights in the full 2.5-minute grid (−106.9 and +85.8 m), which the page's text quotes.

Usage: python3 -I tools/build_geoid.py EGM2008_2p5arcmin.nc4 tools/source/geoid-data.js
Requires numpy, netCDF4.
"""
import sys
import numpy as np
import netCDF4

src, out = sys.argv[1:3]
A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
d = netCDF4.Dataset(src)
la = np.array(d['lat'][:]); lo = np.array(d['lon'][:])
g = np.array(d['geoid_altitude'][:], dtype=float)
assert abs(la[0] + 90) < 1e-6 and abs(lo[0] + 180) < 1e-6, 'expected rows from 90°S and columns from 180°W'
STEP = 2.0
lats = np.arange(-90, 90.001, STEP); lons = np.arange(-180, 179.999, STEP)
grid = np.zeros((len(lats), len(lons)))
LO = ((lo + 180) % 360) - 180
for i, a in enumerate(lats):
    rs = np.where(np.abs(la - a) <= STEP / 2)[0]
    w = np.cos(np.radians(la[rs]))[:, None] + 1e-9            # each row weighted by its area
    for j, b in enumerate(lons):
        dl = np.abs(((LO - b + 180) % 360) - 180)
        cs = np.where(dl <= STEP / 2)[0]
        blk = g[np.ix_(rs, cs)]
        grid[i, j] = (blk * w).sum() / (w.sum() * len(cs))
print(f'grid {grid.shape}, {grid.min():.1f} to {grid.max():.1f} m', file=sys.stderr)
# smoothed with a Gaussian about 2° wide (one cell; across longitude it wraps), so only features wider than a few
# hundred kilometres stay: made 10,000 times taller, anything narrower turns the globe's edge into spikes
SIG = 1.0
k = np.exp(-0.5 * (np.arange(-3, 4) / SIG) ** 2); k /= k.sum()
grid = sum(w * np.roll(grid, o, axis=1) for o, w in zip(range(-3, 4), k))
pad = np.concatenate([grid[3:0:-1], grid, grid[-2:-5:-1]])          # mirrored at the poles
grid = sum(w * pad[3 + o:3 + o + grid.shape[0]] for o, w in zip(range(-3, 4), k))
print(f'smoothed: {grid.min():.1f} to {grid.max():.1f} m', file=sys.stderr)
q = np.round(grid * 2).astype(int)                             # half metres
buf = []
def uu(n):
    while True:
        c = n & 31; n >>= 5
        buf.append(A[c | (32 if n else 0)])
        if not n: break
def sz(n): uu(-n * 2 - 1 if n < 0 else n * 2)
for row in q:
    prev = 0
    for v in row: sz(int(v) - prev); prev = int(v)
lo_i = np.unravel_index(grid.argmin(), grid.shape); hi_i = np.unravel_index(grid.argmax(), grid.shape)
js = ('/* Today\'s gravity shape (the geoid) — GENERATED by tools/build_geoid.py from EGM2008 (Pavlis et al. 2012), '
      'via Zenodo 10.5281/zenodo.14537811 (CC BY 4.0). Mean height above the WGS84 ellipsoid in 2° cells, half metres. */\n'
      f'const GEOID = {{ step: {STEP:g}, w: {len(lons)}, h: {len(lats)}, unit: 0.5, '
      f'low: [{lons[lo_i[1]]:g}, {lats[lo_i[0]]:g}, {grid.min():.1f}], high: [{lons[hi_i[1]]:g}, {lats[hi_i[0]]:g}, {grid.max():.1f}], '
      f'peak: [{g.min():.1f}, {g.max():.1f}], packed: "{"".join(buf)}" }};\n')
open(out, 'w').write(js)
print(f'{len(js) // 1024} KB; lowest {grid.min():.1f} m at {lons[lo_i[1]]:g}E {lats[lo_i[0]]:g}N, highest {grid.max():.1f} m at {lons[hi_i[1]]:g}E {lats[hi_i[0]]:g}N', file=sys.stderr)
