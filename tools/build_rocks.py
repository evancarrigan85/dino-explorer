#!/usr/bin/env python3
"""What the land was like in deep time, read from the rocks.

Source: the lithologic indicators of climate compiled by Boucot, Chen & Scotese (2013), Phanerozoic
Paleoclimate: An Atlas of Lithologic Indicators of Climate (SEPM Concepts in Sedimentology and
Paleontology 11) — 8,698 dated sites, as the CSV distributed with the GPlates web service:

    git clone --depth 1 https://github.com/GPlates/gplates-web-service
    gplates-web-service/django/GWS/data/paleo/Boucot_paleolithology.csv

Each site is a rock that only forms in one kind of climate. They are merged into four the page can
paint: coal (wet, swampy forest) · salt and desert-soil crusts (dry) · bauxite, laterite and kaolin
(hot and wet) · glacial deposits (ice). Sites of one kind within the same 2-degree square are joined
into one, keeping the whole span of their ages. Positions are today's; the page carries each one back
on its plate.

Usage: python3 -I build_rocks.py Boucot_paleolithology.csv rocks-data.js
"""
import sys, csv, collections

src, out = sys.argv[1:3]
KIND = {'C': 0, 'E': 1, 'CA': 1, 'B': 2, 'L': 2, 'K': 2, 'T': 3, 'D': 3, 'G': 3}      # 0 wet · 1 dry · 2 hot and wet · 3 ice
NAMES = ['coal', 'salt and desert crusts', 'bauxite, laterite and kaolin', 'glacial deposits']
CELL = 2.0
cells = collections.defaultdict(list)
used = skipped = 0
for r in csv.DictReader(open(src, encoding='latin-1')):
    k = KIND.get(r['LithCode'])
    try:
        lon, lat, a, b = float(r['X']), float(r['Y']), float(r['FROMAGE']), float(r['TOAGE'])
    except ValueError:
        skipped += 1; continue
    if k is None or not (-90 <= lat <= 90 and -180 <= lon <= 180) or not (a > b >= 0) or a - b > 80:
        skipped += 1; continue                     # an age range wider than 80 million years says too little to paint
    used += 1
    cells[(k, round(lat / CELL), round(lon / CELL))].append((a, b))
pts = []
for (k, cy, cx), spans in cells.items():
    spans.sort(reverse=True)
    cur = list(spans[0])
    for a, b in spans[1:]:
        if a >= cur[1]: cur[1] = min(cur[1], b)    # overlapping or touching: one longer span
        else: pts.append((k, cy, cx, cur[0], cur[1])); cur = [a, b]
    pts.append((k, cy, cx, cur[0], cur[1]))
pts.sort(key=lambda p: (-p[3], p[0], p[1], p[2]))
# one flat list of whole numbers: kind, lat cell, lon cell, from, to (million years, rounded outwards)
flat = []
for k, cy, cx, a, b in pts:
    flat += [k, cy, cx, int(-(-a // 1)), int(b // 1)]
by = collections.Counter(p[0] for p in pts)
js = ('/* Climate read from the rocks — GENERATED by tools/build_rocks.py from Boucot, Chen & Scotese (2013). '
      f'{len(pts)} patches from {used} sites: ' + ', '.join(f'{by[i]} {NAMES[i]}' for i in range(4)) + '. '
      f'Each row: kind, latitude/{CELL:g}, longitude/{CELL:g}, from, to (million years ago). */\n'
      f'const ROCK_CELL = {CELL:g};\nconst ROCKS = [' + ','.join(map(str, flat)) + '];\n')
open(out, 'w').write(js)
print(f'{used} sites used, {skipped} skipped -> {len(pts)} patches, {len(js) // 1024} KB', file=sys.stderr)
for i in range(4): print(f'  {NAMES[i]:32s} {by[i]}', file=sys.stderr)
