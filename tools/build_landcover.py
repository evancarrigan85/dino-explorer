#!/usr/bin/env python3
"""Today's landscapes, from measured climate: rainforest, savanna, desert, steppe, temperate, boreal, tundra, ice.

Source: the Köppen–Geiger climate classification at 100 arc-second resolution for 1986–2010
(Rubel, Brugger, Haslinger & Auer 2017, Meteorologische Zeitschrift 26, doi:10.1127/metz/2016/0816),
as the single image shipped inside the BSD-licensed Python package `kgcpy` (kgcpy/kmz_int_reshape.png):

    pip download kgcpy --no-deps -d kg && python3 -m zipfile -e kg/kgcpy-*.whl kg/x

The 31 climate classes are merged into eight landscapes a child can name, thinned to half a degree,
outlined and packed like the shelf and relief layers. The page only draws this layer for recorded
history (about the last 6,000 years): the climate zones are today's, and further back the deserts
and forests were somewhere else.

Usage: python3 -I build_landcover.py kg/x/kgcpy/kmz_int_reshape.png landcover-data.js
Requires numpy, pillow, shapely, matplotlib.
"""
import sys
import numpy as np
from PIL import Image
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.geometry.polygon import orient
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

src, out = sys.argv[1:3]
Image.MAX_IMAGE_PIXELS = None
# Köppen–Geiger numbers (kgcpy/kg_zoneNum.csv) -> landscape
#  1 Af 2 Am | 3 As 4 Aw | 5 BSh 6 BSk | 7 BWh 8 BWk | 9-11 Cf 12-14 Cs 15-17 Cw | 18-29 D | 30 EF | 31 ET | 32 ocean
LAND = [(1, 'rainforest', [1, 2]), (2, 'savanna', [3, 4]), (3, 'steppe', [5, 6]), (4, 'desert', [7, 8]),
        (5, 'temperate', [9, 10, 11, 15, 16, 17]), (6, 'mediterranean', [12, 13, 14]), (7, 'boreal', list(range(18, 30))), (8, 'tundra', [31]), (9, 'ice', [30])]
STEP = 18                                   # 100 arc-seconds x 18 = half a degree
TOL, MIN_AREA = 0.3, 0.7
kg = np.array(Image.open(src))
H, Wd = kg.shape[0] // STEP, kg.shape[1] // STEP
cls = np.zeros(kg.max() + 1, dtype=np.uint8)
for cid, _, zones in LAND:
    cls[zones] = cid
small = cls[kg]                              # every pixel -> its landscape (0 = sea)
blocks = small[:H * STEP, :Wd * STEP].reshape(H, STEP, Wd, STEP).transpose(0, 2, 1, 3).reshape(H, Wd, STEP * STEP)
# the commonest landscape in each half-degree cell, counting only its land
grid = np.zeros((H, Wd), dtype=np.uint8)
counts = np.stack([(blocks == c).sum(axis=2) for c in range(10)], axis=2)
landfrac = 1 - counts[:, :, 0] / (STEP * STEP)
best = counts[:, :, 1:].argmax(axis=2) + 1
grid[landfrac > 0.15] = best[landfrac > 0.15]
lat = 90 - (np.arange(H) + 0.5) * 180 / H
lon = -180 + (np.arange(Wd) + 0.5) * 360 / Wd
frame = box(-179.9, -89.5, 179.9, 89.5)

def region(cid):
    m = (grid == cid).astype(float)
    m = np.pad(m, 1); la = np.concatenate([[lat[0] + 0.5], lat, [lat[-1] - 0.5]]); lo = np.concatenate([[lon[0] - 0.5], lon, [lon[-1] + 0.5]])
    cs = plt.contourf(lo, la, m, levels=[0.5, 2])
    polys = [Polygon(p).buffer(0) for path in cs.get_paths() for p in path.to_polygons() if len(p) >= 4]
    plt.close('all')
    polys.sort(key=lambda p: -p.area)
    shape = Polygon()
    for p in polys:
        shape = shape.symmetric_difference(p)
    # swell a little so neighbouring landscapes overlap rather than leave cracks of bare paper between them
    return shape.buffer(0.3, join_style=1).intersection(frame)

layers, total = [], 0
for cid, name, _ in LAND:
    g = region(cid).simplify(TOL, preserve_topology=True)
    parts, polys = (g.geoms if isinstance(g, MultiPolygon) else [g]), []
    for q in parts:
        if q.is_empty or q.area < MIN_AREA:
            continue
        q = orient(q, sign=-1.0)
        rings = [q.exterior] + [h for h in q.interiors if Polygon(h).area > MIN_AREA * 4]
        polys.append([[v for x, y in list(r.coords)[:-1] for v in (round(x * 10), round(y * 10))] for r in rings])
    n = sum(len(r) // 2 for p in polys for r in p); total += n
    layers.append([cid, polys])
    print(f'  {name:14s}: {len(polys):4d} polygons, {n:6d} points, {100 * (grid == cid).sum() / (grid > 0).sum():5.1f}% of land cells', file=sys.stderr)
A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
buf = []
def u(n):
    while True:
        c = n & 31; n >>= 5
        buf.append(A[c | (32 if n else 0)])
        if not n: break
def sz(n): u(-n * 2 - 1 if n < 0 else n * 2)
u(len(layers))
for L, polys in layers:
    u(L); u(len(polys))
    for p in polys:
        u(len(p))
        for r in p:
            u(len(r) // 2); px = py = 0
            for i in range(0, len(r), 2):
                sz(r[i] - px); sz(r[i + 1] - py); px, py = r[i], r[i + 1]
js = ('/* Today\'s landscapes — GENERATED by tools/build_landcover.py from the Köppen–Geiger climate map of Rubel et al. (2017). '
      f'{len(layers)} landscapes, {total} points; packed, decoded by the map engine. */\n'
      'const LANDCOVER_PACKED = "' + ''.join(buf) + '";\n')
open(out, 'w').write(js)
print(f'{len(js) // 1024} KB', file=sys.stderr)
