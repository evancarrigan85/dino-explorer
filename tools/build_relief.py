#!/usr/bin/env python3
"""Today's high ground, for the map of the last few million years.

Source: the same 20-arc-minute world elevation grid as build_shelf.py (ETOPO,
NOAA, public domain; examples/etopo20*.gz in github.com/matplotlib/basemap at
tag v1.2.2rel).

For each LEVEL (metres above today's sea) it writes the land higher than that.
The page tints them one over another, so mountains read darker than plains.
Mountains are far younger than continents, so the page only draws this layer
for the Ice Age and after, when the ranges stood where they stand now. The
Greenland and Antarctic ice surfaces are left out: that height is ice, not rock.

Usage: python3 -I build_relief.py etopo20data.gz etopo20lats.gz etopo20lons.gz relief-data.js
Requires numpy, shapely, matplotlib (for contouring).
"""
import sys, gzip
import numpy as np
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.geometry.polygon import orient
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

dfile, latf, lonf, out = sys.argv[1:5]
LEVELS = [600, 1500, 3000]
TOL, MIN_AREA = 0.14, 0.22
d = np.loadtxt(gzip.open(dfile)); la = np.loadtxt(gzip.open(latf)); lo = np.loadtxt(gzip.open(lonf))
lo = ((lo + 180) % 360) - 180
order = np.argsort(lo[:-1]); lo = lo[:-1][order]; d = d[:, :-1][:, order]
lo = np.concatenate([[-180.0], lo, [180.0]])
edge = (d[:, :1] + d[:, -1:]) / 2; d = np.hstack([edge, d, edge])
frame = box(-179.97, -58, 179.97, 86)
greenland = box(-74, 59, -10, 86)

def region(level):
    cs = plt.contourf(lo, la, d, levels=[level, 1e5])
    polys = [Polygon(p).buffer(0) for path in cs.get_paths() for p in path.to_polygons() if len(p) >= 4]
    plt.close('all')
    polys.sort(key=lambda p: -p.area)
    shape = Polygon()
    for p in polys:
        shape = shape.symmetric_difference(p)     # contourf gives exteriors and holes as separate rings
    return shape.intersection(frame).difference(greenland).buffer(-0.04, join_style=2).buffer(0.04, join_style=2)

layers, total = [], 0
for L in LEVELS:
    g = region(L).simplify(TOL, preserve_topology=True)
    parts, polys = (g.geoms if isinstance(g, MultiPolygon) else [g]), []
    for q in parts:
        if q.is_empty or q.area < MIN_AREA:
            continue
        q = orient(q, sign=-1.0)
        rings = [q.exterior] + [h for h in q.interiors if Polygon(h).area > MIN_AREA * 3]
        polys.append([[v for x, y in list(r.coords)[:-1] for v in (round(x * 10), round(y * 10))] for r in rings])
    n = sum(len(r) // 2 for p in polys for r in p); total += n
    layers.append([L, polys])
    print(f'  {L:5d} m: {len(polys)} polygons, {n} points', file=sys.stderr)
# Packed exactly as the shelf data is (see build_shelf.py).
A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
buf = []
def u(n):
    while True:
        c = n & 31; n >>= 5
        buf.append(A[c | (32 if n else 0)])
        if not n: break
def sz(n): u(-n * 2 - 1 if n < 0 else n * 2)
u(len(layers))
for L, polys in layers:
    u(L); u(len(polys))
    for p in polys:
        u(len(p))
        for r in p:
            u(len(r) // 2); px = py = 0
            for i in range(0, len(r), 2):
                sz(r[i] - px); sz(r[i + 1] - py); px, py = r[i], r[i + 1]
js = ('/* Today\'s high ground — GENERATED by tools/build_relief.py from the ETOPO 20-arc-minute grid (NOAA, public domain). '
      f'{len(layers)} heights, {total} points; packed, decoded by the map engine. */\n'
      'const RELIEF_PACKED = "' + ''.join(buf) + '";\n')
open(out, 'w').write(js)
print(f'{len(js) // 1024} KB', file=sys.stderr)
