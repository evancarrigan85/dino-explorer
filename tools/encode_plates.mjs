#!/usr/bin/env node
/* Stage 2 of the map-data pipeline.

   Takes the intermediate JSON from build_plates.py, fixes ring winding to the
   convention d3-geo expects, quantises everything and packs it into one
   compact text stream that the page decodes at start-up.

   Usage: node encode_plates.mjs <stage1.json> <out.js>

   Stream format (unsigned varints, 5 data bits per character, alphabet below;
   signed values are zig-zag encoded):

     nFamilies
       per family:  nKeys, then per key: dt (Myr since previous key),
                    dqx dqy dqz dqw  (signed deltas, quaternion * QS)
     nPolygons
       per polygon: family, hi*10, lo*10+1, nRings,
                    per ring: nPoints, then signed (dLon, dLat) deltas in
                    1/CS degree steps; longitude deltas wrap at +-180.

   A polygon is drawn while  lo < t <= hi  (t in million years ago). */
import fs from 'node:fs';
import { geoArea } from 'd3-geo';

const [,, IN, OUT] = process.argv;
const src = JSON.parse(fs.readFileSync(IN, 'utf8'));
const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
const QS = 4095, CS = 50;

let out = '';
const u = n => { do { let c = n & 31; n >>>= 5; if (n) c |= 32; out += A[c]; } while (n); };
const s = n => u(n < 0 ? (-n * 2 - 1) : n * 2);

let flipped = 0, nPts = 0, nKeys = 0;
const fams = src.families;
u(fams.length);
for (const f of fams) {
  u(f.keys.length);
  let pt = 0, pq = [0, 0, 0, QS];
  for (const [t, x, y, z, w] of f.keys) {
    const q = [x, y, z, w].map(v => Math.round(v * QS));
    u(t - pt); pt = t;
    for (let i = 0; i < 4; i++) { s(q[i] - pq[i]); }
    pq = q; nKeys++;
  }
}
const polys = [];
fams.forEach((f, fi) => f.versions.forEach((v, vi) => {
  const last = vi === f.versions.length - 1;
  for (const rings of v.polys) polys.push({ fi, hi: v.b, lo: v.last ? v.lo - 0.1 : v.lo, rings });
}));
u(polys.length);
for (const p of polys) {
  u(p.fi); u(Math.round(p.hi * 10)); u(Math.round(p.lo * 10) + 1); u(p.rings.length);
  p.rings.forEach((ring, ri) => {
    // d3-geo: a ring whose spherical area exceeds a hemisphere is "inside out".
    const closed = ring.concat([ring[0]]);
    const big = geoArea({ type: 'Polygon', coordinates: [closed] }) > 2 * Math.PI;
    if ((ri === 0 && big) || (ri > 0 && !big)) { ring = ring.slice().reverse(); flipped++; }
    const q = ring.map(([lo, la]) => [Math.round(lo * CS), Math.round(la * CS)]);
    // drop consecutive duplicates created by quantisation
    const r = q.filter((pt, i) => i === 0 || pt[0] !== q[i - 1][0] || pt[1] !== q[i - 1][1]);
    u(r.length);
    let px = 0, py = 0;
    for (const [x, y] of r) {
      let dx = x - px; const W = 360 * CS;
      dx = ((dx % W) + W + W / 2) % W - W / 2;
      s(dx); s(y - py); px = x; py = y; nPts++;
    }
  });
}
const js =
`/* Plate reconstruction data — GENERATED by tools/encode_plates.mjs, do not edit.
   Source: Merdith et al. (2021), "Extending full-plate tectonic models into deep
   time", Earth-Science Reviews 214, 103477 — coastline polygons and plate
   rotations, simplified. ${fams.length} rigid plate families, ${polys.length} polygons,
   ${nPts} points, ${nKeys} rotation keyframes, 0–${src.maxT} million years ago. */
const PLATE_DATA = {maxT:${src.maxT},qs:${QS},cs:${CS},d:"${out}"};
`;
fs.writeFileSync(OUT, js);
console.error(`families ${fams.length} polygons ${polys.length} points ${nPts} keys ${nKeys} flipped ${flipped} -> ${js.length} bytes`);
