#!/usr/bin/env python3
"""Continental shelves for the Ice Age sea-level layer.

Everything shallower than 200 m (Natural Earth's 200 m depth contour,
public domain) is the land that appears when sea level drops in the ice
ages. The real lowstand was about 120 m, so this slightly overstates the
exposed area; the page says so.

Usage: python3 -I build_shelf.py ne_10m_bathymetry_K_200.geojson shelf-data.js
Requires shapely.
"""
import sys, json
from shapely.geometry import shape, box, Polygon, MultiPolygon
from shapely.ops import unary_union
from shapely.geometry.polygon import orient

src, out = sys.argv[1], sys.argv[2]
TOL, MIN_AREA = 0.12, 0.6          # degrees, square degrees
deep = unary_union([shape(f['geometry']).buffer(0) for f in json.load(open(src))['features']])
# Land + shallow seafloor. Natural Earth's deep-ocean polygons stop a hair short
# of the date line, which leaves zero-width slivers running pole to pole; those
# glue continents into one planet-wrapping shape. So: cut a thin gap at +-180,
# remove anything thinner than ~5 km, and leave out Antarctica (under ice anyway).
shelf = (box(-180, -60, 180, 89).difference(deep)
         .difference(box(-180, -90, -179.97, 90)).difference(box(179.97, -90, 180, 90))
         .buffer(-0.05, join_style=2).buffer(0.05, join_style=2))
parts = list(shelf.geoms) if isinstance(shelf, MultiPolygon) else [shelf]
polys, npts = [], 0
for p in parts:
    p = p.simplify(TOL, preserve_topology=True)
    for q in (p.geoms if isinstance(p, MultiPolygon) else [p]):
        if q.is_empty or q.area < MIN_AREA or q.bounds[1] <= -59.9 or q.bounds[3] >= 88.9:
            continue
        q = orient(q, sign=-1.0)                          # clockwise exterior: what d3 expects
        rings = [q.exterior] + [h for h in q.interiors if Polygon(h).area > MIN_AREA * 4]
        enc = [[v for x, y in list(r.coords)[:-1] for v in (round(x * 10), round(y * 10))] for r in rings]
        npts += sum(len(r) // 2 for r in enc)
        polys.append(enc)
js = ('/* Continental shelves (shallower than 200 m) — GENERATED by tools/build_shelf.py from Natural Earth '
      f'bathymetry (public domain). {len(polys)} polygons, {npts} points; lon/lat × 10, clockwise exteriors. */\n'
      'const SHELF_DATA = ' + json.dumps(polys, separators=(',', ':')) + ';\n')
open(out, 'w').write(js)
print(f'{len(polys)} polygons, {npts} points, {len(js)//1024} KB', file=sys.stderr)
