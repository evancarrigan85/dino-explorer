#!/usr/bin/env python3
"""Ice Age shorelines: the land at each sea-level drop.

Source: the 20-arc-minute world elevation/depth grid (ETOPO, NOAA, public
domain) shipped with Basemap 1.2.2 (examples/etopo20*.gz in
github.com/matplotlib/basemap at tag v1.2.2rel).

For each LEVEL (metres below today's sea), it writes the area higher than
that depth — today's land plus the seafloor that would be dry if the sea
fell that far. The page draws the level matching its sea-level curve and
fades in the next one, so the coast moves gradually.

Usage: python3 -I build_shelf.py etopo20data.gz etopo20lats.gz etopo20lons.gz shelf-data.js
Requires numpy, shapely, matplotlib (for contouring).
"""
import sys, gzip, json
import numpy as np
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.ops import unary_union
from shapely.geometry.polygon import orient
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

dfile, latf, lonf, out = sys.argv[1:5]
LEVELS = [10, 20, 30, 40, 50, 60, 80, 100, 125]
TOL, MIN_AREA = 0.12, 0.35
d = np.loadtxt(gzip.open(dfile)); la = np.loadtxt(gzip.open(latf)); lo = np.loadtxt(gzip.open(lonf))
lo = ((lo + 180) % 360) - 180                       # grid starts at 20°E; put it on -180..180
order = np.argsort(lo[:-1]); lo = lo[:-1][order]; d = d[:, :-1][:, order]
lo = np.concatenate([[-180.0], lo, [180.0]])        # close the seam so contours reach the date line
edge = (d[:, :1] + d[:, -1:]) / 2; d = np.hstack([edge, d, edge])
frame = box(-179.97, -60, 179.97, 89)               # see below: keep shapes off the poles and the seam

def region(level):
    cs = plt.contourf(lo, la, d, levels=[-level, 1e5])
    polys = []
    for path in cs.get_paths():
        for poly in path.to_polygons():
            if len(poly) >= 4:
                polys.append(Polygon(poly).buffer(0))
    plt.close('all')
    # contourf returns exteriors and holes as separate rings: rebuild by parity
    polys.sort(key=lambda p: -p.area)
    shape = Polygon()
    for p in polys:
        shape = shape.symmetric_difference(p)
    # zero-width slivers along the date line glue continents into one planet-wrapping
    # shape, so cut a thin gap at +-180, drop Antarctica, and remove anything ~5 km thin.
    return shape.intersection(frame).buffer(-0.05, join_style=2).buffer(0.05, join_style=2)

layers, total = [], 0
for L in LEVELS:
    g = region(L).simplify(TOL, preserve_topology=True)
    parts, polys = (g.geoms if isinstance(g, MultiPolygon) else [g]), []
    for q in parts:
        if q.is_empty or q.area < MIN_AREA or q.bounds[1] <= -59.9 or q.bounds[3] >= 88.9:
            continue
        q = orient(q, sign=-1.0)                    # clockwise exterior: what d3 expects
        rings = [q.exterior] + [h for h in q.interiors if Polygon(h).area > MIN_AREA * 3]
        polys.append([[v for x, y in list(r.coords)[:-1] for v in (round(x * 10), round(y * 10))] for r in rings])
    n = sum(len(r) // 2 for p in polys for r in p); total += n
    layers.append([L, polys])
    print(f'  {L:4d} m: {len(polys)} polygons, {n} points', file=sys.stderr)
# Pack as the plate data is packed: unsigned varints, 5 bits per character,
# zig-zag deltas. Stream: nLevels, then per level: metres, nPolys, per polygon:
# nRings, per ring: nPoints, then (dLon, dLat) pairs in tenths of a degree.
A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
buf = []
def u(n):
    while True:
        c = n & 31; n >>= 5
        buf.append(A[c | (32 if n else 0)])
        if not n: break
def sz(n): u(-n * 2 - 1 if n < 0 else n * 2)
u(len(layers))
for L, polys in layers:
    u(L); u(len(polys))
    for p in polys:
        u(len(p))
        for r in p:
            u(len(r) // 2); px = py = 0
            for i in range(0, len(r), 2):
                sz(r[i] - px); sz(r[i + 1] - py); px, py = r[i], r[i + 1]
js = ('/* Ice Age shorelines — GENERATED by tools/build_shelf.py from the ETOPO 20-arc-minute grid (NOAA, public domain). '
      f'{len(layers)} sea levels, {total} points; packed, decoded by the map engine. */\n'
      'const SHELF_PACKED = "' + ''.join(buf) + '";\n')
open(out, 'w').write(js)
print(f'{len(js) // 1024} KB', file=sys.stderr)
